import io
import datetime as dt

from reportlab.lib.pagesizes import A4
from reportlab.lib.units import cm
from reportlab.lib import colors
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle
)
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle


def generate_prediction_pdf(patient_name: str, prediction: dict) -> bytes:
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=A4, topMargin=2 * cm, bottomMargin=2 * cm)
    styles = getSampleStyleSheet()
    title_style = ParagraphStyle(
        "TitleStyle", parent=styles["Title"], textColor=colors.HexColor("#1B4B43")
    )

    elements = [
        Paragraph("MedAssist — Symptom Assessment Report", title_style),
        Spacer(1, 12),
        Paragraph(f"Patient: {patient_name}", styles["Normal"]),
        Paragraph(
            f"Generated: {dt.datetime.utcnow().strftime('%Y-%m-%d %H:%M UTC')}",
            styles["Normal"],
        ),
        Spacer(1, 16),
        Paragraph("Reported Symptoms", styles["Heading2"]),
        Paragraph(prediction.get("symptoms_list", ""), styles["Normal"]),
        Spacer(1, 12),
        Paragraph("Preliminary Assessment", styles["Heading2"]),
        Paragraph(
            f"Most likely condition: <b>{prediction.get('predicted_disease')}</b> "
            f"(model confidence: {round(prediction.get('confidence', 0) * 100, 1)}%)",
            styles["Normal"],
        ),
        Paragraph(f"Severity: <b>{prediction.get('severity', '').upper()}</b>", styles["Normal"]),
        Spacer(1, 8),
        Paragraph("Recommendation", styles["Heading2"]),
        Paragraph(prediction.get("recommendation", ""), styles["Normal"]),
        Spacer(1, 20),
        Paragraph(
            "<i>Disclaimer: This report is generated by an automated triage "
            "assistant and is not a medical diagnosis. Always consult a "
            "licensed healthcare professional for medical advice.</i>",
            styles["Italic"],
        ),
    ]

    doc.build(elements)
    buffer.seek(0)
    return buffer.read()
